"""Run the worked investigation: ask Claude Code each role's question and save the evidence.

For every role it records the question, every tool call Claude made (arguments, the SQL that ran,
timings, headline numbers), and Claude's final answer, so each claim can be checked.

Usage (SereneDB running, from the repo root):
    python run_investigation.py                 # all three roles
    python run_investigation.py engineer        # one role
    python run_investigation.py engineer --question "What failed for instance 544fd51c-...?"

Writes investigation/<role>.md (readable) and investigation/raw/<role>.jsonl (full stream, for auditing).
"""
import argparse
import json
import pathlib
import shutil
import subprocess
import sys
from datetime import datetime

from logsense import roles

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "investigation"
TOOL_PREFIX = "mcp__serenedb-logs__"

# fields worth showing at a glance for each tool result
HEADLINE_KEYS = ["total_matching_lines", "total_lines_in_window", "total_lines_in_scope", "total_groups",
                "total_lines", "buckets_with_data", "lines_per_bucket", "peak_bucket", "summary", "groups", "returned", "truncated"]


def run_claude(prompt: str) -> list[dict]:
    exe = shutil.which("claude")
    if not exe:
        sys.exit("Claude Code CLI not found on PATH (install it, then run `claude` once to sign in).")
    cmd = [exe, "-p", "--output-format", "stream-json", "--verbose",
            "--mcp-config", str(HERE / ".mcp.json"), "--strict-mcp-config",
            "--allowedTools", f"{TOOL_PREFIX}*"]
    proc = subprocess.run(cmd, input=prompt, capture_output=True, text=True, encoding="utf-8", cwd=HERE)
    events = [json.loads(line) for line in proc.stdout.splitlines() if line.strip().startswith("{")]
    if proc.returncode != 0 and not events:
        sys.exit(f"claude failed:\n{proc.stderr}")
    return events


def extract(events: list[dict]):
    """Pair each MCP tool call with its result; return (calls, final_answer, cost)."""
    calls, by_id, final, cost = [], {}, "", None
    for ev in events:
        msg = ev.get("message") or {}
        for block in msg.get("content") or [] if isinstance(msg.get("content"), list) else []:
            if block.get("type") == "tool_use" and block.get("name", "").startswith(TOOL_PREFIX):
                call = {"tool": block["name"][len(TOOL_PREFIX):], "args": block.get("input", {}), "result": None}
                by_id[block["id"]] = call
                calls.append(call)
            elif block.get("type") == "tool_result" and block.get("tool_use_id") in by_id:
                content = block.get("content")
                text = content if isinstance(content, str) else "".join(
                    c.get("text", "") for c in content or [] if isinstance(c, dict))
                try:
                    parsed = json.loads(text)
                    # some clients wrap plain-text tool output as {"result": "<json>"}
                    if isinstance(parsed, dict) and set(parsed) == {"result"} and isinstance(parsed["result"], str):
                        parsed = json.loads(parsed["result"])
                    by_id[block["tool_use_id"]]["result"] = parsed
                except json.JSONDecodeError:
                    by_id[block["tool_use_id"]]["result"] = {"error": text}
        if ev.get("type") == "result":
            final, cost = ev.get("result", ""), ev.get("total_cost_usd")
    return calls, final, cost


def to_markdown(role: str, question: str, calls, final: str) -> str:
    r = roles.ROLES[role]
    lines = [f"# {r['title']}", "", f"_Generated by `run_investigation.py` on {datetime.now():%Y-%m-%d %H:%M}._", "",
            "## Question", "", f"> {question}", "", "## Answer", "", final.strip(), "",
            f"## Tool calls ({len(calls)})", "",
            "Every call Claude made, in order, with the exact SQL SereneDB ran.", ""]
    for i, c in enumerate(calls, 1):
        res = c["result"] or {}
        lines += [f"### {i}. `{c['tool']}`", "", "```json", json.dumps(c["args"], ensure_ascii=False), "```", ""]
        if "error" in res:
            lines += [f"Error: {res['error']}", ""]
            continue
        head = {k: res[k] for k in HEADLINE_KEYS if k in res}
        if head:
            lines += ["Result headline:", "", "```json", json.dumps(head, ensure_ascii=False)[:1500], "```", ""]
        if res.get("rows"):
            lines += [f"First rows ({min(3, len(res['rows']))} of {len(res['rows'])} returned):", "", "```json"]
            lines += [json.dumps(row, ensure_ascii=False)[:400] for row in res["rows"][:3]]
            lines += ["```", ""]
        for q in res.get("queries", []):
            lines += [f"SQL ({q['ms']} ms, {q['rows']} rows):", "", "```sql", q["sql"], "```", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("roles", nargs="*", metavar="role", help=f"any of {list(roles.ROLES)} (default: all)")
    ap.add_argument("--question", help="Override the default question (only with a single role).")
    args = ap.parse_args()
    args.roles = args.roles or list(roles.ROLES)
    unknown = [r for r in args.roles if r not in roles.ROLES]
    if unknown:
        ap.error(f"unknown role(s) {unknown}; choose from {list(roles.ROLES)}")
    (OUT / "raw").mkdir(parents=True, exist_ok=True)
    for role in args.roles:
        question = args.question or roles.ROLES[role]["default_question"]
        print(f"[{role}] asking Claude...", flush=True)
        events = run_claude(roles.render(role, question))
        (OUT / "raw" / f"{role}.jsonl").write_text("\n".join(json.dumps(e) for e in events), encoding="utf-8")
        calls, final, cost = extract(events)
        (OUT / f"{role}.md").write_text(to_markdown(role, question, calls, final), encoding="utf-8")
        cost_txt = f", ${cost:.2f}" if cost is not None else ""
        print(f"[{role}] {len(calls)} tool calls{cost_txt} -> investigation/{role}.md")


if __name__ == "__main__":
    main()
